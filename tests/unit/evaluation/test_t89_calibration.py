def v080_rows() -> list[dict]:
    rows = []
    for i in range(1, 31):
        scores = {c: 1 + (i * (k + 2)) % 5 for k, c in enumerate(CRITERIA)}
        rows.append(v080_row(i, V080_ROUTES[i % 5], ("dev", "holdout")[i % 2], scores, i % 4 == 0))
    return rows


def table(path: Path) -> list[list[str]]:
    return list(csv.reader(io.StringIO(path.read_bytes().decode("utf-8-sig"), newline=""), delimiter=";"))


def save_table(path: Path, rows: list[list[str]]) -> None:
    with path.open("w", encoding="utf-8-sig", newline="") as handle:
        csv.writer(handle, delimiter=";", lineterminator="\r\n").writerows(rows)


def v080_fixture(tmp_path: Path, db: Path):
    data = v080_rows()
    report = tmp_path / "v080-all.json"
    report.write_text(json.dumps({"config": {"mode": "scripted"}, "summary": {}, "cases": data}), encoding="utf-8")
    sample, meta = cal.make_sample(report, 24, cal.DEFAULT_SEED)
    path = tmp_path / "amostra.csv"
    cal.write_csv(path, sample, meta)
    blank_hash = hashlib.sha256(path.read_bytes()).hexdigest()
    conn = connect(db)
    judge = scripted_judge(PROMPTS, NullMeter(), rubric="v3")
    for r in data:
        save_evaluation(conn, request_id=r["request_id"], judge=judge, record=r["judge"], data=r["judge_input"])
    by = {r["request_id"]: r["judge"] for r in data}
    rows = table(path)
    at = next(i for i, t in enumerate(rows) if t and t[0] == "sample_id")
    head = rows[at]
    for n, t in enumerate(rows[at + 1 :]):
        if n == 3:
            continue  # one row left blank
        j = by[t[head.index("request_id")]]
        for k, c in enumerate(CRITERIA):
            t[head.index(c)] = str(max(1, min(5, j["scores"][c] + ((n + k) % 3) - 1)))
        t[head.index("unsupported_claim")] = "sim" if (j["unsupported_claim"] != (n % 5 == 0)) else "nao"
    save_table(path, rows)
    return conn, path, blank_hash


