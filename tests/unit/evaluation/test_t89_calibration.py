def fill_scores(path: Path, values: dict[str, dict[str, str]]) -> None:
    rows = table(path)
    at = next(i for i, row in enumerate(rows) if row and row[0] == "sample_id")
    head = rows[at]
    for row in rows[at + 1 :]:
        for column, value in values.get(row[0], {}).items():
            row[head.index(column)] = value
    save_table(path, rows)


def fill_marks(path: Path, marks: dict[str, dict[int, str]], added: dict[str, list[tuple[str, str]]] | None = None):
    rows = table(path)
    at = next(i for i, row in enumerate(rows) if row and row[0] == "sample_id")
    head = rows[at]
    for row in rows[at + 1 :]:
        mark = marks.get(row[0], {}).get(int(row[head.index("n")] or 0))
        if mark:
            row[head.index("verdict")] = mark
    for sample_id, extra in (added or {}).items():
        request_id = next(r[1] for r in rows[at + 1 :] if r[0] == sample_id)
        for text, mark in extra:
            rows.append([sample_id, request_id, "", "", "", mark, text])
    save_table(path, rows)


def type_verdicts(path: Path) -> None:
    """What the panel's CSV carries (task 89 round 5, P2-1): a model rater's verdict comes from its `unsupported_claim`
    column alone, so the tests type it in every rated row, as its marks give it (a claim that is not `standard`, or
    one it added, marked generic or not_found)."""
    rows = table(claims_csv(path))
    at = next(i for i, row in enumerate(rows) if row and row[0] == "sample_id")
    head = rows[at]
    flagged = {
        row[0]
        for row in rows[at + 1 :]
        if row and row[head.index("kind")] != "standard" and row[head.index("verdict")] in {"generic", "not_found"}
    }
    rows = table(path)
    at = next(i for i, row in enumerate(rows) if row and row[0] == "sample_id")
    head = rows[at]
    for row in rows[at + 1 :]:
        if row and any(row[head.index(criterion)] for criterion in GOOD):
            row[head.index("unsupported_claim")] = "sim" if row[0] in flagged else "nao"
    save_table(path, rows)


def judge_of(provider: str, model: str, rubric: str) -> Judge:
    claims = load_prompt(PROMPTS, "judge_claims", "1") if rubric == "5" else None
    return Judge(None, provider, model, load_prompt(PROMPTS, "judge", rubric), NullMeter(), "x", claims_prompt=claims)


def record(tag: str, index: int, rubric: str, unsupported: set[int], scores: dict, *, rename: bool = False) -> dict:
    """A completed judgement of answer `index`: under v5 the claims with `generic` on the numbers in `unsupported`."""
    out = {
        "evaluation_id": f"eval_{tag}_{index}",
        "rubric_version": rubric,
        "repetition": 1,
        "model_used": "m",
        "state": "completed",
        "scores": scores,
        "reasons": {c: "r" for c in CRITERIA},
        "cost_usd": 0.001,
        "usage": None,
        "error": None,
    }
    if rubric == "5":
        listed = claims_of(index)
        if rename:
            listed[1] = {**listed[1], "text": "Verifique o app, por favor."}
        verdicts = [
            {"n": c["n"], "verdict": "generic" if c["n"] in unsupported else "supported", "support": ""}
            for c in listed
        ]
        out["claims"] = {"claims": listed, "claim_verdicts": verdicts}
        out["unsupported_claim"] = any(n in unsupported for n in (1, 2))
    else:
        out["unsupported_claim"] = bool(unsupported)
    return out


