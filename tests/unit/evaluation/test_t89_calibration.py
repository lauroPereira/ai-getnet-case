def panel_members(tmp_path: Path) -> dict[tuple[str, str], Path]:
    """Two members of the panel, each with a blank copy of the sealed sample and of the earlier one (of `two`)."""
    files = {}
    for member in ("m1", "m2"):
        for name, folder in (("sealed", "selada"), ("old", "antiga")):
            source = tmp_path / folder / "sample.csv"
            copy = tmp_path / member / name / "sample.csv"
            copy.parent.mkdir(parents=True)
            copy.write_bytes(source.read_bytes())
            claims_csv(copy).write_bytes(claims_csv(source).read_bytes())
            files[(member, name)] = copy
    return files


def merge_args(first: Path, second: Path, out: Path | None, *, samples: bool = True, **values) -> argparse.Namespace:
    given = {"merge_panel": [str(claims_csv(first)), str(claims_csv(second))], "out": str(out) if out else None}
    if samples:
        given["sample_csv"] = [str(first), str(second)]
    return calibrate_args(**(given | values))


def rows_by(path: Path, key=lambda row: row[0]) -> tuple[list[str], dict]:
    rows = table(path)
    at = next(i for i, row in enumerate(rows) if row and row[0] == "sample_id")
    return rows[at], {key(row): row for row in rows[at + 1 :] if row}


def sample_line(path: Path) -> str:
    return next(row[0] for row in table(path) if row and row[0].startswith("# amostra:"))


