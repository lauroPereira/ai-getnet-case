def test_a_panel_verdict_left_blank_by_an_added_claim_is_never_computed_from_the_marks(two, tmp_path):
    """Round 5 (P2-1): the members differ only by a claim one of them added, so every listed mark agrees and the
    verdict is blank in the panel's CSV. The panel's verdict comes from that column alone: no verdict (NULL), the
    divergence goes to the adjudication and nothing turns "não" by itself."""
    settings = two["settings"]
    sealed = two["files"][("owner", "sealed")]
    first, *others = ids_in(sealed)
    prepare(two)  # the human: every claim supported, verdict "não"
    members = panel_members(tmp_path)
    m1, m2 = members[("m1", "sealed")], members[("m2", "sealed")]
    fill_member(m1, mark_all(m1))
    fill_marks(claims_csv(m1), {}, added={first: [("O prazo de repasse é de 2 dias.", "not_found")]})  # "sim"
    fill_member(m2, mark_all(m2))  # "não"
    panel = tmp_path / "painel" / "sample.csv"
    assert cli.cmd_eval_calibrate(settings, merge_args(m1, m2, panel)) == 0
    head, rows = rows_by(panel)
    assert rows[first][head.index("unsupported_claim")] == "" and rows[first][head.index("relevance")] == "5"
    head, claim_rows = rows_by(claims_csv(panel), key=lambda row: (row[0], row[2]))
    assert [claim_rows[(first, n)][head.index("verdict")] for n in "123"] == ["supported"] * 3
    seal = two["root"] / packets.SEAL_FILE
    _, filled, _, _ = cal.read_rater(rater_files(PANEL, panel, claims_csv(panel)), seal)
    verdicts = {rating.sample_id: rating.unsupported_claim for rating in filled.ratings}
    assert verdicts == {first: None, **dict.fromkeys(others, False)}  # blank stays blank; typed "nao" is False
    entries = [(OWNER, sealed, claims_csv(sealed)), (PANEL, panel, claims_csv(panel))]
    request_id = dict(zip(ids_in(sealed), cal.sample_request_ids(sealed), strict=True))[first]
    with pytest.raises(cal.CalibrationError) as caught:
        import_entries(two, entries)
    assert caught.value.messages == [
        f"{first} ({request_id}): owner e painel divergem em unsupported_claim não × sem rótulo; a adjudicação "
        "(--adjudication, colunas request_id, gold_verdict, gold_scores, reason) é obrigatória."
    ]
    assert stored_count(settings) == 0
    result = import_entries(two, entries, adjudicate(tmp_path / "adj.csv", request_id, verdict="sim"))
    assert result["gold"][request_id]["unsupported_claim"] is True
    conn = connect(settings.db_path)
    try:
        stored = conn.execute(
            "SELECT unsupported_claim FROM calibrations WHERE rater LIKE 'painel:%' AND request_id=?", (request_id,)
        ).fetchone()
    finally:
        conn.close()
    assert stored is not None and stored[0] is None  # the panel gave no verdict: NULL, not 0
    # the marks only check the typed verdict: one both members marked against the answer contradicts "nao"
    fill_marks(claims_csv(panel), {others[0]: {2: "generic"}})
    with pytest.raises(cal.CalibrationError, match="O veredito do painel vem da coluna"):
        cal.read_rater(rater_files(PANEL, panel, claims_csv(panel)), seal)


