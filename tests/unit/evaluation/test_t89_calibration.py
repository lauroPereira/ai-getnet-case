class Counting:
    """The scripted model, counting the calls by output schema."""

    def __init__(self, llm):
        self.llm, self.calls = llm, []

    def parse(self, spec, schema, meter):
        self.calls.append(schema.__name__)
        return self.llm.parse(spec, schema, meter)


