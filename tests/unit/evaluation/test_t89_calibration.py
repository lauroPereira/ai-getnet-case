def answer_row(index: int, route: str, split: str = "dev", *, claims: bool = True, case: str | None = None) -> dict:
    """One answer of a campaign report. With `claims`, its judgement is a judge.v5 one with its claims recorded."""
    message = f"Pergunta {index} sobre o valor?"
    reply = f"O valor líquido é R$ {index},00. Confira o aplicativo {index}. Posso ajudar em algo mais?"
    judge = {
        "evaluation_id": f"eval_t89{index:04d}",
        "rubric_version": "5" if claims else "3",
        "repetition": 1,
        "provider": "sentinel",
        "model": "sentinel-model",
        "model_used": "sentinel-model",
        "state": "completed",
        "scores": {c: 2 for c in CRITERIA},
        "reasons": {c: f"{SENTINEL}-REASON-{index}" for c in CRITERIA},
        "unsupported_claim": True,
        "cost_usd": 0.0,
        "error": None,
    }
    if claims:
        verdicts = [{"n": c["n"], "verdict": "not_found", "support": f"{SENTINEL}-SUPPORT"} for c in claims_of(index)]
        judge["claims"] = {"claims": claims_of(index), "claim_verdicts": verdicts}
    return {
        "id": case or f"T89-{index:03d}",
        "repetition": 1,
        "request_id": f"req_t89{index:04d}",
        "split": split,
        "route": route,
        "language": "pt",
        "message": message,
        "answer": reply,
        "judge_input": {
            "merchant_message": message,
            "status": "answered",
            "route": route,
            "sources": [f"Fonte {index}"],
            "evidence": [
                {"kind": "passage", "label": f"doc-{index}", "text": "Trecho longo " * 20 + " [...cut]", "cut": True},
                {"kind": "tool_result", "label": "get_receivables", "text": f'{{"net": "R$ {index},00"}}'},
                {
                    "kind": "web_page",
                    "label": "Página citada",
                    "title": "Página citada",
                    "url": f"https://example.com/p{index}",
                    "text": "Texto da página.",
                },
                {"kind": "web_summary", "label": "web search summary (written by the assistant)", "text": "Resumo."},
            ],
            "evidence_truncation": {
                "limit_chars": 6000,
                "original_chars": 9000,
                "kept_chars": 6000,
                "items": 4,
                "items_cut": 1,
                "truncated": True,
            },
            "evidence_notes": [],
            "reply": reply,
        },
        "judge": judge,
    }


def write_report(path: Path, rows: list[dict]) -> Path:
    config = {"mode": "scripted", "model": "scripted-v1", "agent_provider": "scripted"}
    path.write_text(json.dumps({"config": config, "summary": {}, "cases": rows}), encoding="utf-8")
    return path


def population(count: int = 40) -> list[dict]:
    return [answer_row(i, ROUTES[i % 5], ("dev", "holdout")[i % 2]) for i in range(1, count + 1)]


def test_the_enriched_routes_hold_at_least_half_of_the_sample(tmp_path):
    rows = population()
    report = write_report(tmp_path / "campanha.json", rows)
    enriched = ("knowledge", "knowledge_and_support")
    drawn, meta = cal.draw(report, 12, 7, enrich=list(enriched))
    share = sum(row["route"] in enriched for row in drawn)
    assert len(drawn) == 12 and share >= 6 and len({row["request_id"] for row in drawn}) == 12
    assert {row["route"] for row in drawn} - set(enriched)  # the other half is drawn from every route left
    assert meta["enriched"] == f"knowledge+knowledge_and_support-{share}"
    again, _ = cal.draw(report, 12, 7, enrich=list(enriched))
    assert [r["request_id"] for r in again] == [r["request_id"] for r in drawn]  # the seed decides
    _, plain_meta = cal.draw(report, 12, 7)
    assert "enriched" not in plain_meta
    stamp = cal.sample_stamp(cal.sample_rows(drawn), meta)
    assert f"enriquecidas=knowledge+knowledge_and_support-{share}" in stamp
    with pytest.raises(cal.CalibrationError, match="precisa de pelo menos 21"):
        cal.draw(report, 41, 7, enrich=list(enriched))  # 16 answers in those routes, half of 41 is 21


def test_the_answers_already_calibrated_stay_out_by_request_id(tmp_path):
    rows = population()
    report = write_report(tmp_path / "campanha.json", rows)
    earlier = tmp_path / "v080.csv"
    sample, meta = cal.make_sample(write_report(tmp_path / "antiga.json", rows[:6]), 6, 1)
    cal.write_csv(earlier, sample, meta)
    # round 2 (decision of the Supervisor): a new answer to a case of the earlier sample (same case id, another
    # request) is a new answer for the judge, and stays in
    rows.append(answer_row(99, "knowledge", case=rows[0]["id"]))
    write_report(report, rows)
    drawn, meta = cal.draw(report, 41 - 6, 7, exclude=[earlier])
    taken = {row["request_id"] for row in drawn}
    assert not taken & {row["request_id"] for row in rows[:6]}
    assert "req_t890099" in taken and meta["excluded"] == 6 and meta["eligible"] == 41 - 6
    assert "excluidas=6" in cal.sample_stamp(cal.sample_rows(drawn), meta)


