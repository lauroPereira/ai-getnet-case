def adjudicate_rows(path: Path, rows: dict[str, dict[str, str]]) -> Path:
    head = ["request_id", "gold_verdict", "gold_scores", "reason", "gold_claims"]
    lines = [";".join(head)] + [
        ";".join([request_id, g.get("verdict", ""), g.get("scores", ""), REASON, g.get("claims", "")])
        for request_id, g in rows.items()
    ]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


