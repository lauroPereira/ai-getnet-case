def pair_labels(report: str) -> set[str]:
    """The first cell of every row of the pair tables (by criterion, verdict and claim)."""
    labels = set()
    for line in report.splitlines():
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if line.startswith("| ") and len(cells) > 2 and " × " in cells[1]:
            labels.add(cells[1])  # by criterion: the pair is the second cell
        if line.startswith("| ") and " × " in cells[0]:
            labels.add(cells[0])
    return labels


