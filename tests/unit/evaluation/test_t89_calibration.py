def claims_csv(path: Path) -> Path:
    return path.with_name("sample-claims.csv")


def ids_in(path: Path) -> list[str]:
    return [r[0] for r in table(path) if r and r[0].startswith("S")]


def everyone(path: Path, **override) -> dict[str, dict[str, str]]:
    return {sample_id: dict(GOOD) | override.get(sample_id, {}) for sample_id in ids_in(path)}


def mark_all(path: Path, flagged: dict[str, int] | None = None) -> dict[str, dict[int, str]]:
    """Every claim supported, except claim `n` marked generic in the answers of `flagged`."""
    flagged = flagged or {}
    return {
        s: {1: "supported", 2: "generic" if flagged.get(s) == 2 else "supported", 3: "supported"} for s in ids_in(path)
    }


