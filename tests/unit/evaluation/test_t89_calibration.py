def scenario_cases() -> dict[str, list[dict]]:
    """The cases of tests/scenarios by report: the development run (`eval --split all --include-replan`, 44) and the
    holdout_v080 run (25). Each answer takes the first route the case accepts."""
    folder = PROJECT_ROOT / "tests" / "scenarios"

    def read(*names: str) -> list[dict]:
        return [
            json.loads(line)
            for name in names
            for line in (folder / name).read_text(encoding="utf-8").splitlines()
            if line.strip()
        ]

    return {
        "dev": read("replan.jsonl", "challenge_examples.jsonl", "core_cases.jsonl", "business_journeys.jsonl"),
        "v080": read("holdout_v080.jsonl"),
    }


def campaign_report(path: Path, cases: list[dict], start: int, repeat: int = 3) -> Path:
    rows = []
    for k, case in enumerate(cases):
        for repetition in range(1, repeat + 1):
            row = answer_row(start + k * 10 + repetition, case["accepted_routes"][0], case["split"], case=case["id"])
            rows.append(row | {"repetition": repetition})
    return write_report(path, rows)


